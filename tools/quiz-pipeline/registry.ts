import { mkdir, readFile, rename, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));

export const REPO_ROOT = join(HERE, '..', '..');
export const GENERATED_DIR = join(REPO_ROOT, 'packages', 'quiz-content', 'src', 'content', 'generated');
export const REGISTRY_PATH = join(GENERATED_DIR, 'index.ts');

export interface GeneratedEntry {
  moduleId: string;
  topicId: string;
  exportName: string;
}

async function writeAtomic(path: string, content: string): Promise<void> {
  await mkdir(dirname(path), { recursive: true });
  const temporary = `${path}.${process.pid}.tmp`;
  await writeFile(temporary, content, 'utf8');
  await rename(temporary, path);
}

async function readIfExists(path: string): Promise<string | null> {
  try {
    return await readFile(path, 'utf8');
  } catch {
    return null;
  }
}

/**
 * Reads the generated-topic registry. The file is generated by this pipeline,
 * so a small regex parser is enough; anything it cannot parse is dropped on
 * the next write.
 */
export async function readRegistry(path = REGISTRY_PATH): Promise<GeneratedEntry[]> {
  const text = await readIfExists(path);
  if (!text) return [];

  const imports = new Map<string, string>();
  for (const match of text.matchAll(/import \{ (\w+) \} from '\.\/([^']+)';/g)) {
    imports.set(match[1], match[2]);
  }

  const seen = new Set<string>();
  const entries: GeneratedEntry[] = [];
  for (const match of text.matchAll(/\{ moduleId: '([^']+)', topic: (\w+) \}/g)) {
    const [, moduleId, exportName] = match;
    const topicId = imports.get(exportName);
    if (!topicId || seen.has(topicId)) continue;
    seen.add(topicId);
    entries.push({ moduleId, topicId, exportName });
  }
  return entries;
}

export async function writeRegistry(
  entries: GeneratedEntry[],
  path = REGISTRY_PATH,
): Promise<void> {
  const sorted = [...entries].sort(
    (left, right) =>
      left.moduleId.localeCompare(right.moduleId) || left.topicId.localeCompare(right.topicId),
  );
  const lines = [
    "import type { QuizTopic } from '@ua/quiz-content/types';",
    ...(sorted.length
      ? ['', ...sorted.map((entry) => `import { ${entry.exportName} } from './${entry.topicId}';`)]
      : []),
    '',
    'export interface GeneratedQuizTopic {',
    '  moduleId: string;',
    '  topic: QuizTopic;',
    '}',
    '',
    '/**',
    ' * Topics written by `bun run quiz:from-pdf`. The CLI owns this file; edit a',
    ' * generated topic in its own file, and rerun the command with --force to',
    ' * replace it.',
    ' */',
    ...(sorted.length
      ? [
          'export const generatedTopics: GeneratedQuizTopic[] = [',
          ...sorted.map((entry) => `  { moduleId: '${entry.moduleId}', topic: ${entry.exportName} },`),
          '];',
        ]
      : ['export const generatedTopics: GeneratedQuizTopic[] = [];']),
    '',
  ];
  await writeAtomic(path, lines.join('\n'));
}

/** `prag-sitzung-3` → `pragSitzung3`. */
export function topicExportName(topicId: string): string {
  const words = topicId.split(/[^A-Za-z0-9]+/).filter(Boolean);
  const camel = words
    .map((word, index) =>
      index === 0
        ? word.charAt(0).toLowerCase() + word.slice(1)
        : word.charAt(0).toUpperCase() + word.slice(1),
    )
    .join('');
  const safe = camel || 'generatedTopic';
  return /^[0-9]/.test(safe) ? `topic${safe}` : safe;
}

export function uniqueExportName(topicId: string, used: Set<string>): string {
  const base = topicExportName(topicId);
  let candidate = base;
  let suffix = 2;
  while (used.has(candidate)) {
    candidate = `${base}${suffix}`;
    suffix += 1;
  }
  return candidate;
}

export async function writeTopicFile(topicId: string, source: string): Promise<string> {
  const path = join(GENERATED_DIR, `${topicId}.ts`);
  await writeAtomic(path, source);
  return path;
}

export async function topicFileExists(topicId: string): Promise<boolean> {
  return (await readIfExists(join(GENERATED_DIR, `${topicId}.ts`))) !== null;
}
