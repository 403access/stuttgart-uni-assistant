import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

import { buildArticulationSiteData } from '@ua/feature-articulation';

/**
 * Writes the articulation studio snapshot for the static marketing site.
 *
 * The website has no build step, so the data is committed as a plain script
 * (`apps/site/assets/articulation.js`) that the page loads next to its own
 * `articulation.js` renderer. `bun run check:quiz` fails when the file drifts
 * from the app's content — run this after changing sounds or poses:
 *
 *   bun run site:articulation
 */
const TARGET = resolve('apps/site/assets/articulation.js');

export function serializeArticulationSiteData(): string {
  return [
    '/* @generated by tools/export-articulation-site.ts — do not edit.',
    '   Snapshot of the app\'s articulation studio; run `bun run site:articulation` after changing it. */',
    `window.UA_ARTICULATION = ${JSON.stringify(buildArticulationSiteData())};`,
    '',
  ].join('\n');
}

export function readArticulationSiteSnapshot(source: string): unknown {
  const marker = 'window.UA_ARTICULATION = ';
  const start = source.indexOf(marker);
  if (start === -1) return undefined;
  const end = source.lastIndexOf(';');
  try {
    return JSON.parse(source.slice(start + marker.length, end));
  } catch {
    return undefined;
  }
}

if (process.argv[1]?.endsWith('export-articulation-site.ts')) {
  const data = buildArticulationSiteData();
  writeFileSync(TARGET, serializeArticulationSiteData());
  console.log(
    `Wrote ${TARGET}: ${data.sounds.length} sounds, ${data.regions.length} regions.`,
  );
}
