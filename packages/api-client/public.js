import { createClient } from './client.js';

/** Public endpoints used by the app and by command-line tools. */
export function createPublicClient(options = {}) {
  const client = createClient(options);
  return {
    ...client,
    health: () => client.get('/health'),
    api: () => client.get('/v1/api'),
    news: () => client.get('/v1/news'),
    campusConfig: () => client.get('/v1/campus/config'),
    campusLogin: (body) => client.post('/v1/campus/login', body),
    campusCredentials: (body) => client.post('/v1/campus/credentials', body),
    campusStructure: (body) => client.post('/v1/campus/structure', body),
    campusCourses: (body) => client.post('/v1/campus/courses', body),
    campusCourseGroups: (body) => client.post('/v1/campus/course-groups', body),
    campusStudies: () => client.get('/v1/campus/studies'),
    campusSync: (body) => client.post('/v1/campus/sync', body),
    campusTree: (query) => client.get('/v1/campus/tree', { query }),
    campusCoursesAll: (query) => client.get('/v1/campus/courses/all', { query }),
    campusCalls: (query) => client.get('/v1/campus/calls', { query }),
    campusCalendarEvents: (query) => client.get('/v1/campus/calendar-events', { query }),
    campusExport: (body) => client.post('/v1/campus/calendar-export', body),
    campusExportSync: (body) => client.post('/v1/campus/calendar-sync', body),
    iliasConfig: () => client.get('/v1/ilias/config'),
    iliasDashboard: () => client.get('/v1/ilias/dashboard'),
    iliasContent: (query) => client.get('/v1/ilias/content', { query }),
    iliasMembers: (query) => client.get('/v1/ilias/members', { query }),
    iliasProfile: (query) => client.get('/v1/ilias/profile', { query }),
    iliasImage: (query) => client.get('/v1/ilias/image', { query }),
    iliasFile: (query) => client.get('/v1/ilias/file', { query }),
    iliasViewer: (query) => client.get('/v1/ilias/viewer', { query }),
    mailConfig: () => client.get('/v1/mail/config'),
    mailFolders: () => client.get('/v1/mail/folders'),
    mailCredentials: (body) => client.post('/v1/mail/credentials', body),
    mailMessages: (query) => client.get('/v1/mail/messages', { query }),
    mailBody: (query) => client.get('/v1/mail/body', { query }),
    mailSeen: (body) => client.post('/v1/mail/seen', body),
    mailSend: (body) => client.post('/v1/mail/send', body),
    mailLogout: () => client.post('/v1/mail/logout', {}),
    authSession: (body) => client.post('/v1/auth/session', body),
    authMe: () => client.get('/v1/auth/me'),
    authLogout: () => client.post('/v1/auth/logout', {}),
    authLinks: (body) => client.post('/v1/auth/links', body),
    authSync: (body) => client.post('/v1/auth/sync', body),
    oidcConfig: () => client.get('/v1/oidc/config'),
    oidcStart: (body) => client.post('/v1/oidc/start', body),
    oidcExchange: (body) => client.post('/v1/oidc/exchange', body),
    oidcLogout: (body) => client.post('/v1/oidc/logout', body),
    quizCatalog: () => client.get('/v1/quiz/catalog'),
    quizSync: (body) => client.post('/v1/quiz/sync', body),
    assist: (body) => client.post('/v1/assist', body),
  };
}
