import { createClient } from './client.js';

/** Operator endpoints. Authentication is the HttpOnly admin cookie. */
export function createAdminClient({ baseUrl = '', ...options } = {}) {
  const client = createClient({ baseUrl, credentials: 'same-origin', ...options });
  const id = (value) => encodeURIComponent(String(value));
  return {
    ...client,
    login: (token) => client.post('/v1/admin/login', { token }),
    logout: () => client.post('/v1/admin/logout', {}),
    overview: () => client.get('/v1/admin/overview'),
    ilias: () => client.get('/v1/admin/ilias'),
    users: (query) => client.get('/v1/admin/users', { query }),
    createUser: (body) => client.post('/v1/admin/users', body),
    user: (userId, query) => client.get(`/v1/admin/users/${id(userId)}`, { query }),
    updateUser: (userId, body) => client.post(`/v1/admin/users/${id(userId)}`, body),
    deleteUser: (userId) => client.del(`/v1/admin/users/${id(userId)}`),
    userStudies: (userId) => client.get(`/v1/admin/users/${id(userId)}/studies`),
    userCourses: (userId, query) => client.get(`/v1/admin/users/${id(userId)}/courses`, { query }),
    userNodes: (userId, query) => client.get(`/v1/admin/users/${id(userId)}/nodes`, { query }),
    userEvents: (userId, query) => client.get(`/v1/admin/users/${id(userId)}/events`, { query }),
    userCalls: (userId, query) => client.get(`/v1/admin/users/${id(userId)}/calls`, { query }),
    userRevokeSessions: (userId) => client.post(`/v1/admin/users/${id(userId)}/sessions/revoke`, {}),
    userRevokeSession: (userId, sessionId) => client.del(`/v1/admin/users/${id(userId)}/sessions/${id(sessionId)}`),
    userLinkPlatform: (userId, body) => client.post(`/v1/admin/users/${id(userId)}/platforms`, body),
    userTouchPlatform: (userId, platform) => client.post(`/v1/admin/users/${id(userId)}/platforms/${id(platform)}/touch`, {}),
    userUnlinkPlatform: (userId, platform) => client.del(`/v1/admin/users/${id(userId)}/platforms/${id(platform)}`),
    userDisconnectCampus: (userId) => client.post(`/v1/admin/users/${id(userId)}/campus/disconnect`, {}),
    userDisconnectIlias: (userId) => client.post(`/v1/admin/users/${id(userId)}/ilias/disconnect`, {}),
    userIliasContent: (userId, query) => client.get(`/v1/admin/users/${id(userId)}/ilias/content`, { query }),
    userIliasMembers: (userId, query) => client.get(`/v1/admin/users/${id(userId)}/ilias/members`, { query }),
    userIliasProfile: (userId, query) => client.get(`/v1/admin/users/${id(userId)}/ilias/profile`, { query }),
    userClearPortal: (userId, studyId) => client.post(`/v1/admin/users/${id(userId)}/portal/clear`, { studyId }),
    userClearEvents: (userId) => client.post(`/v1/admin/users/${id(userId)}/portal/events/clear`, {}),
    userClearCalls: (userId) => client.post(`/v1/admin/users/${id(userId)}/portal/calls/clear`, {}),
    userSync: (userId, body) => client.post(`/v1/admin/users/${id(userId)}/sync`, body),
    devices: (query) => client.get('/v1/admin/devices', { query }),
    device: (deviceId) => client.get(`/v1/admin/devices/${id(deviceId)}`),
    revokeDevice: (deviceId) => client.del(`/v1/admin/devices/${id(deviceId)}`),
    audit: (query) => client.get('/v1/admin/audit', { query }),
    logs: (query) => client.get('/v1/admin/logs', { query }),
    clearLogs: (query) => client.del('/v1/admin/logs', { query }),
    news: (query) => client.get('/v1/admin/news', { query }),
    createNews: (body) => client.post('/v1/admin/news', body),
    updateNews: (newsId, body) => client.post(`/v1/admin/news/${id(newsId)}`, body),
    deleteNews: (newsId) => client.del(`/v1/admin/news/${id(newsId)}`),
    system: () => client.get('/v1/admin/system'),
    environment: (reveal = false) => client.get('/v1/admin/environment', { query: reveal ? { reveal: 1 } : undefined }),
    mailLogout: () => client.post('/v1/admin/system/mail/logout', {}),
    syncJobs: () => client.get('/v1/admin/sync-jobs'),
    cancelSync: (jobId) => client.del(`/v1/admin/sync-jobs/${id(jobId)}`),
    quizOverview: () => client.get('/v1/admin/quiz/overview'),
    quizModules: () => client.get('/v1/admin/quiz/modules'),
    quizTopics: (query) => client.get('/v1/admin/quiz/topics', { query }),
    quizAttempts: (query) => client.get('/v1/admin/quiz/attempts', { query }),
    quizSessions: (query) => client.get('/v1/admin/quiz/sessions', { query }),
    quizTopic: (topicId) => client.get(`/v1/admin/quiz/topics/${id(topicId)}`),
    quizCreateTopic: (body) => client.post('/v1/admin/quiz/topics', body),
    quizCreateQuestion: (body) => client.post('/v1/admin/quiz/questions', body),
    quizUpdateQuestion: (questionId, body) => client.post(`/v1/admin/quiz/questions/${id(questionId)}`, body),
    quizDeleteQuestion: (questionId) => client.del(`/v1/admin/quiz/questions/${id(questionId)}`),
    quizUpdateTopic: (topicId, body) => client.post(`/v1/admin/quiz/topics/${id(topicId)}`, body),
    quizDeleteTopic: (topicId) => client.del(`/v1/admin/quiz/topics/${id(topicId)}`),
    quizSeed: () => client.post('/v1/admin/quiz/seed', {}),
  };
}
